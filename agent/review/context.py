"""Опора ревью: фрагменты документов и кода из индекса базы PR и места вызова (spec FR-04, plan D-05).

Три источника:
1. **Индекс базы** (документы + код репозитория на общем предке PR) — поиск по запросам из
   diff: путь файла, имена изменённых функций и классов, заметные идентификаторы
   добавленных строк, заголовок PR. Фрагменты самих изменённых файлов не берутся: их
   новую версию ревьюер видит в diff и в контексте функций.
2. **Места вызова** изменённых функций в базе — `git_grep` + `git_show` по строкам
   (git-сервер MCP): кто зовёт то, что поменяли.
3. **Контекст функций на голове** — тело функции или класса Python вокруг изменённых строк
   (из текста головы, разбор `ast`): diff даёт три строки окружения, а ошибка часто видна
   только во всей функции.

Каждому ревьюеру — свой отбор (до 12 фрагментов), нумерация общая: источник в находке
проверяется по номеру.
"""

from __future__ import annotations

import ast
import re
import time
from collections import Counter
from dataclasses import dataclass, field
from typing import Any, Protocol

from agent.review.source import ВходPR, ФайлPR, GitЧтение, добавленные, изменённые_номера

РЕВЬЮЕРЫ = ("баги", "архитектура", "рекомендации")
НА_ЗАПРОС = 8
НА_РЕВЬЮЕРА = 12
ФУНКЦИЙ_ДЛЯ_ВЫЗОВОВ = 8
МЕСТ_НА_ФУНКЦИЮ = 4
ОКРУЖЕНИЕ_ВЫЗОВА = 6
СТРОК_КОНТЕКСТА = 120
СИМВОЛОВ_ФРАГМЕНТА = 2400
# Запросы, которые архитектурному ревьюеру нужны всегда: правила проекта лежат в
# «Конституции дня» спек и в ARCHITECTURE.md, а не рядом с изменённым кодом.
ЗАПРОСЫ_ПРАВИЛ = ("Конституция дня постоянные ограничения правила",
                  "Устройство агента слои модули кто кому передаёт")

_ИДЕНТИФИКАТОР = re.compile(r"[A-Za-zА-Яа-яЁё_][0-9A-Za-zА-Яа-яЁё_]{3,}")
_ЗАГОЛОВОК_УЧАСТКА = re.compile(r"^@@[^@]*@@\s*(?:async\s+)?(?:def|class)\s+([0-9A-Za-zА-Яа-яЁё_]+)")
_ОПРЕДЕЛЕНИЕ = re.compile(r"^\s*(?:async\s+)?(?:def|class)\s+([0-9A-Za-zА-Яа-яЁё_]+)")
_ШУМ = frozenset("self None True False return import from class print with open isinstance "
                 "len range dict list str int текст итог данные значение путь".split())


class Поисковик(Protocol):
    def найти(self, запрос: str, сколько: int = 10, исключить: Any = ()) -> list[Any]: ...


@dataclass
class Фрагмент:
    номер: int
    источник: str
    раздел: str
    текст: str
    вид: str          # «документ», «код», «вызов»
    оценка: float = 0.0

    @property
    def подпись(self) -> str:
        return f"{self.источник} › {self.раздел}" if self.раздел else self.источник

    def to_dict(self) -> dict[str, Any]:
        return {"номер": self.номер, "источник": self.источник, "раздел": self.раздел, "вид": self.вид,
                "оценка": self.оценка}


@dataclass
class КонтекстФункции:
    путь: str
    имя: str
    с: int
    по: int
    текст: str


@dataclass
class Опора:
    фрагменты: list[Фрагмент] = field(default_factory=list)
    на_ревьюера: dict[str, list[int]] = field(default_factory=dict)
    функции: list[КонтекстФункции] = field(default_factory=list)
    запросы: list[str] = field(default_factory=list)
    изменённые_имена: list[str] = field(default_factory=list)
    секунд: dict[str, float] = field(default_factory=dict)

    def для(self, ревьюер: str) -> list[Фрагмент]:
        по_номеру = {ф.номер: ф for ф in self.фрагменты}
        return [по_номеру[н] for н in self.на_ревьюера.get(ревьюер, []) if н in по_номеру]

    def метрики(self) -> dict[str, Any]:
        виды = Counter(ф.вид for ф in self.фрагменты)
        return {"фрагментов": len(self.фрагменты), "документов": виды.get("документ", 0),
                "кода": виды.get("код", 0), "вызовов": виды.get("вызов", 0), "запросов": len(self.запросы),
                "функций": len(self.функции), "секунд": dict(self.секунд)}


# --- что изменилось ------------------------------------------------------------------

def функции_головы(ф: ФайлPR) -> list[КонтекстФункции]:
    """Самые внутренние def/class Python, в которых PR тронул строки (на голове)."""
    if not ф.голова or not ф.путь.endswith(".py") or not ф.diff:
        return []
    try:
        дерево = ast.parse(ф.голова)
    except (SyntaxError, ValueError):
        return []
    узлы = [у for у in ast.walk(дерево) if isinstance(у, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef))]
    строки = ф.голова.splitlines()
    итог: dict[tuple[int, int], КонтекстФункции] = {}
    for номер in изменённые_номера(ф.diff):
        задетые = [у for у in узлы if у.lineno <= номер <= (у.end_lineno or у.lineno)]
        if not задетые:
            continue
        # Самая внутренняя: класс на 500 строк не нужен, если поменяли один метод.
        у = min(задетые, key=lambda у: (у.end_lineno or у.lineno) - у.lineno)
        с, по = у.lineno, у.end_lineno or у.lineno
        if по - с + 1 > СТРОК_КОНТЕКСТА:
            с, по = max(с, номер - СТРОК_КОНТЕКСТА // 2), min(по, номер + СТРОК_КОНТЕКСТА // 2)
        if any(к.с <= номер <= к.по for к in итог.values()):
            continue
        итог[(с, по)] = КонтекстФункции(ф.путь, у.name, с, по, "\n".join(строки[с - 1:по]))
    return sorted(итог.values(), key=lambda к: к.с)


def изменённые_имена(ф: ФайлPR) -> list[str]:
    """Имена функций и классов, которые PR меняет: из заголовков участков, из добавленных
    определений и из разбора головы."""
    имена: list[str] = []
    for строка in ф.diff.splitlines():
        м = _ЗАГОЛОВОК_УЧАСТКА.match(строка)
        if м:
            имена.append(м.group(1))
    for _, строка in добавленные(ф.diff):
        м = _ОПРЕДЕЛЕНИЕ.match(строка)
        if м:
            имена.append(м.group(1))
    имена += [к.имя for к in функции_головы(ф)]
    return list(dict.fromkeys(и for и in имена if not и.startswith("__")))


def _идентификаторы(ф: ФайлPR, сколько: int = 8) -> list[str]:
    счёт: Counter[str] = Counter()
    for _, строка in добавленные(ф.diff):
        счёт.update(и for и in _ИДЕНТИФИКАТОР.findall(строка) if и not in _ШУМ)
    for строка in ф.diff.splitlines():
        if строка.startswith("-") and not строка.startswith("---"):
            счёт.update(и for и in _ИДЕНТИФИКАТОР.findall(строка[1:]) if и not in _ШУМ)
    return [и for и, _ in счёт.most_common(сколько)]


def запросы(вход: ВходPR) -> list[tuple[str, str]]:
    """(запрос, путь файла) — по одному на просмотренный файл; плюс заголовок PR."""
    итог = []
    for ф in вход.просмотренные:
        модуль = ф.путь.rsplit("/", 1)[-1].rsplit(".", 1)[0]
        части = [ф.путь.replace("/", " "), модуль, *изменённые_имена(ф)[:6], *_идентификаторы(ф)]
        итог.append((" ".join(dict.fromkeys(части)), ф.путь))
    if вход.заголовок.strip():
        итог.append((вход.заголовок.strip()[:200], ""))
    return итог


# --- места вызова --------------------------------------------------------------------

def места_вызова(git: GitЧтение, вход: ВходPR, имена: list[str]) -> list[Фрагмент]:
    """Где в базе зовут изменённые функции: строка вызова с окружением (номера проставит Опора)."""
    итог: list[Фрагмент] = []
    for имя in имена[:ФУНКЦИЙ_ДЛЯ_ВЫЗОВОВ]:
        if len(имя) < 4:
            continue
        вход.вызовы.append("git_grep")
        ок, _, найдено = git.вызвать("git__git_grep", {"pattern": имя, "ref": вход.база, "limit": 40})
        if not ок:
            continue
        # Места вызова — только в коде (в документах имя функции — упоминание, не вызов), без
        # тестов и самого определения.
        места = [м for м in найдено.get("места", [])
                 if _вид(м["путь"]) == "код" and not _ОПРЕДЕЛЕНИЕ.match(м.get("текст", ""))
                 and not м["путь"].rsplit("/", 1)[-1].startswith(("test", "check_"))]
        for м in места[:МЕСТ_НА_ФУНКЦИЮ]:
            с = max(1, м["строка"] - ОКРУЖЕНИЕ_ВЫЗОВА)
            вход.вызовы.append("git_show")
            ок, _, кусок = git.вызвать("git__git_show", {"path": м["путь"], "ref": вход.база,
                                                         "start_line": с, "end_line": м["строка"] + ОКРУЖЕНИЕ_ВЫЗОВА})
            if ок and кусок.get("текст"):
                итог.append(Фрагмент(0, м["путь"], f"вызов {имя}, строки {с}–{м['строка'] + ОКРУЖЕНИЕ_ВЫЗОВА}",
                                     кусок["текст"], "вызов"))
    return итог


# --- сборка ---------------------------------------------------------------------------

def _вид(источник: str) -> str:
    return "код" if источник.endswith((".py", ".js", ".mjs", ".sh", ".html")) else "документ"


def собрать(вход: ВходPR, поисковик: Поисковик | None, git: GitЧтение | None = None) -> Опора:
    """Опора для трёх ревьюеров. Без поисковика (индекс не собрался) — только места вызова и
    контекст функций; это видно в метриках, а ревью помечается «без опоры на документы»."""
    опора = Опора()
    # Исключаются фрагменты только изменённого КОДА: его новая версия — в diff и контексте
    # функций. Изменённый документ остаётся версией базы: это правила, по которым смотрят PR,
    # и сам PR их переписать не может.
    изменённые = {ф.путь for ф in вход.файлы if ф.вид == "код"}
    for ф in вход.просмотренные:
        опора.функции += функции_головы(ф)
        опора.изменённые_имена += [и for и in изменённые_имена(ф) if и not in опора.изменённые_имена]

    найдено: dict[tuple[str, str, str], Фрагмент] = {}
    по_запросу: list[list[tuple[str, str, str]]] = []
    т = time.monotonic()
    if поисковик is not None:
        список = запросы(вход) + [(з, "") for з in ЗАПРОСЫ_ПРАВИЛ]
        for запрос, _ in список:
            опора.запросы.append(запрос)
            ключи = []
            for н in поисковик.найти(запрос, НА_ЗАПРОС, исключить=изменённые):
                ч = н.чанк
                ключ = (ч.источник, ч.раздел, ч.текст[:80])
                if ключ not in найдено:
                    найдено[ключ] = Фрагмент(0, ч.источник, ч.раздел, ч.текст[:СИМВОЛОВ_ФРАГМЕНТА],
                                             _вид(ч.источник), float(н.оценка))
                else:
                    найдено[ключ].оценка = max(найдено[ключ].оценка, float(н.оценка))
                ключи.append(ключ)
            по_запросу.append(ключи)
    опора.секунд["поиск"] = round(time.monotonic() - т, 2)

    т = time.monotonic()
    вызовы = места_вызова(git, вход, опора.изменённые_имена) if git is not None else []
    опора.секунд["вызовы"] = round(time.monotonic() - т, 2)

    # Порядок важности: сначала лучшие по каждому запросу (круговой обход), чтобы один
    # длинный файл не забрал все места.
    порядок: list[tuple[str, str, str]] = []
    for уровень in range(НА_ЗАПРОС):
        for ключи in по_запросу:
            if уровень < len(ключи) and ключи[уровень] not in порядок:
                порядок.append(ключи[уровень])
    все = [найдено[к] for к in порядок] + вызовы
    for номер, фрагмент in enumerate(все, 1):
        фрагмент.номер = номер
    опора.фрагменты = все

    документы = [ф.номер for ф in все if ф.вид == "документ"]
    код = [ф.номер for ф in все if ф.вид == "код"]
    места = [ф.номер for ф in все if ф.вид == "вызов"]
    номер_ключа = {к: найдено[к].номер for к in порядок}
    правила = list(dict.fromkeys(номер_ключа[к] for ключи in по_запросу[-len(ЗАПРОСЫ_ПРАВИЛ):]
                                 for к in ключи[:3] if найдено[к].вид == "документ")) if по_запросу else []

    def отбор(*группы: list[int]) -> list[int]:
        итог: list[int] = []
        for группа, сколько in группы:
            for н in группа:
                if len([x for x in итог if x in группа]) >= сколько or len(итог) >= НА_РЕВЬЮЕРА:
                    break
                if н not in итог:
                    итог.append(н)
        return sorted(итог)

    опора.на_ревьюера = {
        "баги": отбор((места, 6), (код, 4), (документы, 3)),
        "архитектура": отбор((правила, 4), (документы, 5), (код, 3)),
        "рекомендации": отбор((документы, 5), (код, 4), (места, 3)),
    }
    return опора
